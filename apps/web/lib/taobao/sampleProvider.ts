const byId = new Map(items.map((entry) => [entry.itemId, entry]));

export const sampleProvider: TaobaoProvider = {
  id: 'sample',
  label: 'Жишиг өгөгдөл',
  sample: true,
  async search({ category, query }) {
    const needle = query.trim().toLocaleLowerCase();
    return items
      .filter((entry) => entry.category === category)
      .filter(
        (entry) =>
          !needle ||
          `${entry.titleZh} ${entry.mn.name} ${entry.mn.description}`.toLocaleLowerCase().includes(needle)
      )
      .map(
        ({ mn: _mn, ...rest }): TaobaoItem => ({ ...rest, url: null, image: null, sample: true })
      );
  },
};

/** Ready-made translation for a sample listing (used when no Claude key is set). */
export function sampleTranslation(itemId: string): TaobaoTranslation | null {
  const entry = byId.get(itemId);
  if (!entry) return null;
  return {
    itemId,
    name: entry.mn.name,
    description: entry.mn.description,
    details: [...entry.mn.details],
    variants: [...entry.mn.variants],
  };
}
